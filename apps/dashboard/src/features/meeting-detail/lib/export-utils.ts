import { MeetingItem, SummaryTemplateContent } from '../../../types/meeting';
import { toast } from '@meetflow/ui';

function sanitizeFilename(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, '-')
    .replace(/-+/g, '-')
    .substring(0, 50);
}

function triggerDownload(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function formatSecondsToTime(seconds: number): string {
  const mins = Math.floor(seconds / 60);
  const secs = Math.floor(seconds % 60);
  return `${mins}:${secs.toString().padStart(2, '0')}`;
}

export function buildMarkdownSummary(
  meeting: MeetingItem,
  template: SummaryTemplateContent
): string {
  const dateStr = new Date(meeting.startDate).toLocaleString();
  const participantsStr = meeting.participants.map((p) => p.name).join(', ');

  let md = `# ${meeting.title}\n\n`;
  md += `**Date:** ${dateStr}  \n`;
  md += `**Duration:** ${formatSecondsToTime(meeting.durationSeconds)}  \n`;
  md += `**Platform:** ${meeting.platform.toUpperCase()}  \n`;
  md += `**Participants:** ${participantsStr}\n\n`;
  md += `---\n\n`;
  md += `## Meeting Summary (${template.label})\n\n`;

  for (const section of template.sections) {
    md += `### ${section.title}\n\n`;
    for (const item of section.items) {
      const ts =
        item.timestampSeconds !== undefined
          ? ` [${formatSecondsToTime(item.timestampSeconds)}]`
          : '';
      const speaker = item.speakerName ? `*${item.speakerName}*: ` : '';
      md += `- ${speaker}${item.text}${ts}\n`;
    }
    md += `\n`;
  }

  if (meeting.actionItems && meeting.actionItems.length > 0) {
    md += `## Action Items\n\n`;
    for (const act of meeting.actionItems) {
      const check = act.completed ? '[x]' : '[ ]';
      const assignee = act.assigneeName ? ` (@${act.assigneeName})` : '';
      const due = act.dueDate ? ` - Due: ${act.dueDate}` : '';
      const ts =
        act.timestampSeconds !== undefined
          ? ` [${formatSecondsToTime(act.timestampSeconds)}]`
          : '';
      md += `- ${check} **${act.title}**${assignee}${due}${ts}\n`;
    }
    md += `\n`;
  }

  md += `---\n*Generated by MeetFlow AI Workspace*\n`;
  return md;
}

export function downloadSummaryMarkdown(meeting: MeetingItem, template: SummaryTemplateContent) {
  const md = buildMarkdownSummary(meeting, template);
  const safeTitle = sanitizeFilename(meeting.title);
  const dateStr = meeting.startDate.split('T')[0];
  const filename = `meetflow-summary-${safeTitle}-${dateStr}.md`;

  triggerDownload(md, filename, 'text/markdown;charset=utf-8');
  toast.success('Summary notes downloaded (.md)');
}

export function downloadTranscriptText(meeting: MeetingItem) {
  if (!meeting.transcriptTurns || meeting.transcriptTurns.length === 0) {
    toast.error('No transcript available to export');
    return;
  }

  const dateStr = new Date(meeting.startDate).toLocaleString();
  let text = `TRANSCRIPT: ${meeting.title}\n`;
  text += `Date: ${dateStr}\n`;
  text += `Duration: ${formatSecondsToTime(meeting.durationSeconds)}\n\n`;
  text += `============================================================\n\n`;

  for (const turn of meeting.transcriptTurns) {
    const time = `[${formatSecondsToTime(turn.startTime)} - ${formatSecondsToTime(turn.endTime)}]`;
    text += `${time} ${turn.speakerName}:\n${turn.text}\n\n`;
  }

  const safeTitle = sanitizeFilename(meeting.title);
  const filename = `meetflow-transcript-${safeTitle}.txt`;
  triggerDownload(text, filename, 'text/plain;charset=utf-8');
  toast.success('Plain-text transcript downloaded (.txt)');
}

export async function copySummaryToClipboard(
  meeting: MeetingItem,
  template: SummaryTemplateContent
): Promise<boolean> {
  const md = buildMarkdownSummary(meeting, template);
  try {
    await navigator.clipboard.writeText(md);
    toast.success('Summary copied to clipboard');
    return true;
  } catch {
    toast.error('Failed to copy to clipboard');
    return false;
  }
}
